// embed: turn a file into a C byte array, so the binary can carry it verbatim

#include <errno.h>
#include <stdio.h>
#include <string.h>

static int fail(const char *);

// A byte array rather than a string literal: -Wpedantic caps literals at the
// 4095 characters ISO C promises, and the reference config runs past that.
int
main(int argc, char **argv)
{
  FILE *in, *out;
  unsigned long n = 0;
  int c;

  if(argc != 4)
  {
    fprintf(stderr, "usage: %s <header-out> <file-in> <symbol>\n", argv[0]);
    return(2);
  }

  if(!(in = fopen(argv[2], "rb"))) return(fail(argv[2]));

  if(!(out = fopen(argv[1], "w"))) return(fail(argv[1]));

  fprintf(out, "// generated by embed — do not edit\n"
               "static const unsigned char %s[] =\n{", argv[3]);

  while((c = getc(in)) != EOF)
    fprintf(out, "%s0x%02x,", n++ % 12 ? " " : "\n  ", (unsigned)c);

  if(ferror(in)) return(fail(argv[2]));

  if(fprintf(out, "\n};\n") < 0 || fclose(out) != 0) return(fail(argv[1]));

  fclose(in);

  return(0);
}

static int
fail(const char *path)
{
  fprintf(stderr, "embed: %s: %s\n", path, strerror(errno));

  return(1);
}
