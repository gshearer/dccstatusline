// dccstatusline — MIT
// buildnum: generate version.h, counting builds where a counter file exists

#include <errno.h>
#include <inttypes.h>
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static bool counter_bump(const char *, uint64_t *);
static bool header_write(const char *, const char *);
static bool fail(const char *);

// The counter is opt-in by presence. A tree holding the counter file counts its
// builds; a release tarball or a fresh clone has none and builds as plain
// vX.Y.Z, the same bytes every time, as a reproducible package needs. *n is 0
// when there is no counter. An unreadable or garbled counter is not an error:
// it restarts at 1, and this write heals it.
static bool
counter_bump(const char *path, uint64_t *n)
{
  FILE *f = fopen(path, "r");

  *n = 0;

  if(!f && errno == ENOENT) return(true);

  if(f)
  {
    char buf[32];

    if(fgets(buf, sizeof buf, f))
    {
      char *end = NULL;
      unsigned long long v;

      errno = 0;
      v = strtoull(buf, &end, 10);

      if(end != buf && errno != ERANGE) *n = (uint64_t)v;
    }

    fclose(f);
  }

  (*n)++;

  if(!(f = fopen(path, "w"))) return(fail(path));

  if(fprintf(f, "%" PRIu64 "\n", *n) < 0 || fclose(f) != 0) return(fail(path));

  return(true);
}

// Rewritten only when its text changes: without a counter the header is
// constant, and an untouched mtime spares main.c a recompile on every ninja run.
static bool
header_write(const char *path, const char *text)
{
  size_t len = strlen(text);
  FILE *f = fopen(path, "r");

  if(f)
  {
    char old[512];
    size_t got = fread(old, 1, sizeof old, f);

    fclose(f);

    if(got == len && memcmp(old, text, len) == 0) return(true);
  }

  if(!(f = fopen(path, "w"))) return(fail(path));

  if(fputs(text, f) == EOF || fclose(f) != 0) return(fail(path));

  return(true);
}

static bool
fail(const char *path)
{
  fprintf(stderr, "buildnum: %s: %s\n", path, strerror(errno));

  return(false);
}

int
main(int argc, char **argv)
{
  char text[512], build[32] = "";
  uint64_t n;
  int len;

  if(argc != 4)
  {
    fprintf(stderr, "usage: %s <version.h-out> <counter-file> <version>\n", argv[0]);
    return(EXIT_FAILURE);
  }

  if(!counter_bump(argv[2], &n)) return(EXIT_FAILURE);

  if(n) snprintf(build, sizeof build, " (build #%" PRIu64 ")", n);

  len = snprintf(text, sizeof text,
                 "// generated by buildnum — do not edit\n"
                 "#define DCC_VERSION \"%s\"\n"
                 "#define DCC_BUILD_STRING \"dccstatusline v%s%s\"\n",
                 argv[3], argv[3], build);

  if(len < 0 || (size_t)len >= sizeof text)
  {
    fprintf(stderr, "buildnum: version string too long\n");
    return(EXIT_FAILURE);
  }

  return(header_write(argv[1], text) ? EXIT_SUCCESS : EXIT_FAILURE);
}
